export type Fill = (key: string, what: string) => string;

const ARBITRATION =
  "Any dispute shall be referred to a sole arbitrator appointed by mutual consent, seated in Hyderabad, under the Arbitration and Conciliation Act 1996. The courts are not shut out: either party may approach the courts at Hyderabad for urgent interim relief.";
const LAW = "This Agreement is governed by the laws of India, and the courts at Hyderabad, Telangana have jurisdiction.";
const GENERAL = "This is the entire agreement between the parties. If any clause is found invalid, the rest remains in force. Notices shall be in writing to the addresses above.";
const SIGNS = (a: string, b: string) => [`SIGN: ${a}`, `SIGN: ${b}`, "SIGN: Witness 1", "SIGN: Witness 2"];
const SIGN_NOTES = [
  "- Pay stamp duty at the current Telangana rate for this kind of document and use stamp paper or an e-stamp of that value before anyone signs. Unstamped agreements cannot be relied on in court. (STAMP-35)",
  "- Both parties should sign with valid ID, or e-sign through a valid Aadhaar e-Sign provider. (ITA-10A)",
  "- Fill in every highlighted blank before signing.",
];

export function freelanceDraft(f: Fill): string {
  return [
    "TITLE: FREELANCE SERVICES AGREEMENT",
    `This Agreement is made on [[to be filled: date]] at Hyderabad, Telangana, between ${f("client_name", "client's full name and address")} (the **Client**) and ${f("freelancer_name", "freelancer's full name and address")} (the **Freelancer**).`,
    "## 1. Services and deliverables",
    `The Freelancer shall provide the following services and deliverables: ${f("scope", "description of the work and deliverables")}, by ${f("deadline", "delivery dates")}.`,
    "> why: The work and its delivery must be clear, or a court may find the promise too vague to enforce. (Source: ICA-10)",
    "## 2. Fee and payment",
    `The Client shall pay a fee of ${f("fee", "fee")}. The Freelancer shall invoice on [[to be filled: milestones or dates]], and the Client shall pay each invoice within [[to be filled: number of days]] days. Late payment carries reasonable interest of [[to be filled: rate]].`,
    "> why: A fixed payment time and a reasonable remedy for delay can be enforced, while a vague one cannot. (Source: ICA-73, MSMED-15)",
    "## 3. Ownership of the work",
    "On full payment the Freelancer assigns to the Client the copyright in the deliverables described in clause 1. This assignment covers all rights to use, adapt, publish and copy those deliverables, for a period of [[to be filled: number of years, or perpetual]], across the territory of [[to be filled: India, or worldwide]]. The Freelancer keeps their own pre-existing tools and materials.",
    "> why: Copyright passes only by a signed writing that names the work, the rights, the period and the territory. (Source: CRA-17, CRA-19)",
    "## 4. Independent contractor",
    "The Freelancer works as an independent contractor, not as an employee of the Client, and is responsible for their own tools, taxes and working hours.",
    "> why: Whether someone is an employee depends on the real relationship, so the contract should reflect it honestly. (Source: CRA-17, LAB-CODES)",
    "## 5. Confidentiality",
    "Each party shall keep the other's confidential information private and use it only for this work. This duty continues for [[to be filled: number of years]] years after this Agreement ends.",
    "> why: Confidentiality is lawful and enforceable even though a ban on working for others after the contract ends is void. (Source: ICA-27)",
    "## 6. Ending the agreement",
    "Either party may terminate this Agreement by giving [[to be filled: number of days]] days' written notice. The Client shall pay for work properly completed up to the date of termination.",
    "> why: A clear exit and payment for work done avoids disputes about walking away. (Source: ICA-73)",
    "## 7. Dispute resolution",
    ARBITRATION,
    "> why: Arbitration is allowed, but a clause letting one side decide finally is void. (Source: ARB-7, ICA-28)",
    "## 8. Governing law and courts",
    LAW,
    "> why: The courts must have a real connection with the matter. (Source: CPC-16)",
    "## 9. General",
    GENERAL,
    "> why: Written terms generally prevail over oral promises. (Source: BSA-94)",
    ...SIGNS("Client", "Freelancer"),
    "===BEFORE YOU SIGN===",
    ...SIGN_NOTES,
    "- Decide who bears GST and whether tax is deducted from the fee, and ask a chartered accountant. (TAX-TDS)",
    "- If the Freelancer is a registered micro or small enterprise, payment cannot be delayed beyond 45 days. (MSMED-15)",
  ].join("\n");
}

export function ndaDraft(f: Fill): string {
  return [
    "TITLE: NON-DISCLOSURE AGREEMENT",
    `This Agreement is made on [[to be filled: date]] at Hyderabad, Telangana, between ${f("disclosing_party", "disclosing party's full name and address")} (the **Discloser**) and ${f("receiving_party", "receiving party's full name and address")} (the **Recipient**).`,
    "## 1. Purpose",
    `The Discloser will share information with the Recipient only for this purpose: ${f("purpose", "the purpose of sharing")}. The mutual promises in this Agreement are the consideration for both sides.`,
    "> why: A stated purpose limits how the information may be used, and an agreement needs a lawful object. (Source: ICA-10, ICA-23)",
    "## 2. What is confidential",
    "**Confidential Information** means the non-public information the Discloser shares with the Recipient for the purpose above, in any form, that is marked or would reasonably be understood to be confidential.",
    "> why: A clear definition is what a court will look at first. (Source: ICA-10)",
    "## 3. What is not confidential",
    "Information is not confidential if it is already in the public domain, was already known to the Recipient, was independently developed by the Recipient, or was lawfully received from someone else without a duty of secrecy.",
    "> why: A promise to keep secret what is already public serves no lawful object. (Source: ICA-23)",
    "## 4. The Recipient's duty",
    "The Recipient shall not disclose the Confidential Information to anyone else, shall keep it secure, and shall use it only for the purpose above. It may be shared only with those who need it and who are bound to keep it secret.",
    "> why: This is the core promise that the agreement exists to protect. (Source: ICA-10)",
    "## 5. How long it lasts",
    `The Recipient's duties continue for a period of ${f("duration", "duration, for example 3 years")} from the date of this Agreement.`,
    "> why: A reasonable fixed period is more likely to be enforced than an unlimited one. (Source: ICA-27, ICA-74)",
    "## 6. Return or destruction",
    "On written request, the Recipient shall return or destroy the Confidential Information and confirm in writing that it has done so.",
    "> why: It gives the Discloser a practical way to get its information back. (Source: ICA-73)",
    "## 7. Disclosure required by law",
    "The Recipient may disclose Confidential Information if required by law, a court order or a lawful government request, after telling the Discloser first where the law allows.",
    "> why: A promise cannot require someone to break the law. (Source: ICA-23)",
    "## 8. Remedies",
    "If this Agreement is broken, the Discloser may ask a court for an injunction and for reasonable compensation for proven loss.",
    "> why: Courts award reasonable compensation, not a fixed penalty. (Source: ICA-74, SRA-14)",
    "## 9. Dispute resolution",
    ARBITRATION,
    "> why: Arbitration is allowed, but a clause letting one side decide finally is void. (Source: ARB-7, ICA-28)",
    "## 10. Governing law and courts",
    LAW,
    "> why: The courts must have a real connection with the matter. (Source: CPC-16)",
    "## 11. General",
    GENERAL,
    "> why: Written terms generally prevail over oral promises. (Source: BSA-94)",
    ...SIGNS("Discloser", "Recipient"),
    "===BEFORE YOU SIGN===",
    ...SIGN_NOTES,
    "- If the information includes personal data of customers or staff, the Digital Personal Data Protection Act applies. Ask an advocate. (DPDP-ACT)",
  ].join("\n");
}

export function employmentDraft(f: Fill): string {
  return [
    "TITLE: EMPLOYMENT AGREEMENT",
    `This Agreement is made on [[to be filled: date]] at Hyderabad, Telangana, between ${f("employer_name", "employer's full name and address")} (the **Employer**) and ${f("employee_name", "employee's full name and address")} (the **Employee**).`,
    "## 1. Appointment",
    `The Employer appoints the Employee in the position of ${f("role", "job title")}, based at [[to be filled: place of work]], starting on ${f("start_date", "start date")}. The main duties are: [[to be filled: duties]].`,
    "> why: A clear role and place of work avoid later disputes. (Source: ICA-10)",
    "## 2. Salary",
    `The Employee shall receive a salary of ${f("salary", "salary and its breakdown")} per month, paid on or before [[to be filled: pay date]] of each month, less deductions the law requires. The salary shall never be below the minimum wage notified for the work.`,
    "> why: Pay below the notified minimum wage is not lawful, and the labour codes now govern wages. (Source: LAB-CODES)",
    "## 3. Probation",
    "The first [[to be filled: probation period, or write none]] months are a probation period. At its end the Employer shall confirm the Employee in writing or tell the Employee in writing that the probation is extended or ended.",
    "> why: A written outcome avoids disputes about confirmation. (Source: ICA-10)",
    "## 4. Notice period",
    "After confirmation, either party may end this employment by giving [[to be filled: notice period]] of written notice or pay in place of notice. Any amount due for leaving early shall be limited to the Employer's reasonable, proven loss.",
    "> why: A large fixed sum for leaving early can be reduced by a court to reasonable compensation. (Source: ICA-74)",
    "## 5. Leave and working hours",
    "The Employee is entitled to leave and working hours as stated in the Employer's written policy and as the law requires: [[to be filled: leave entitlement and working hours]].",
    "> why: Leave and hours are set by law as a minimum, and the contract may give more but not less. (Source: LAB-CODES)",
    "## 6. Statutory benefits",
    "The Employee is entitled to provident fund, ESI where applicable, and gratuity as the law provides. Nothing in this Agreement waives or reduces any benefit the law gives the Employee.",
    "> why: A right to statutory benefits cannot be signed away. (Source: GRA-4, SSC-53, LAB-CODES)",
    "## 7. Confidentiality and work created",
    "The Employee shall keep the Employer's confidential information private, during and after employment. Intellectual property and work product the Employee creates in the course of the job belong to the Employer, as the law provides for work made in employment.",
    "> why: Work made in employment belongs to the employer unless agreed otherwise, and confidentiality is lawful after the job ends. (Source: CRA-17, ICA-27)",
    "## 8. Ending the employment",
    "The Employer may end this employment for misconduct only after giving the Employee a fair chance to respond in writing. On any exit the Employer shall pay what is due within the time the law sets.",
    "> why: Fair process and prompt payment of dues protect both sides. (Source: LAB-CODES)",
    "## 9. Dispute resolution",
    ARBITRATION,
    "> why: Arbitration is allowed, but a clause letting one side decide finally is void. (Source: ARB-7, ICA-28)",
    "## 10. Governing law and courts",
    LAW,
    "> why: The courts must have a real connection with the matter. (Source: CPC-16)",
    "## 11. General",
    GENERAL,
    "> why: Written terms generally prevail over oral promises. (Source: BSA-94)",
    ...SIGNS("Employer", "Employee"),
    "===BEFORE YOU SIGN===",
    ...SIGN_NOTES,
    "- Check Telangana's shops and establishments rules and the labour-code rules that now apply to this employer. (LAB-CODES)",
    "- Gratuity rules are still settling between the 1972 Act and the Social Security Code. Do not add a rupee ceiling without checking. (GRA-4, SSC-53)",
  ].join("\n");
}

